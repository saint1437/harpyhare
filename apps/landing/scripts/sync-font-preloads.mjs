/**
 * The `<link rel="preload">` list for each locale's fonts, generated out of the
 * build's own `@font-face` rules.
 *
 * WHY THIS EXISTS. `next/font` emits one preload per declared subset, and the
 * set it emits is read from `next-font-manifest.json`. Under the webpack builder
 * that manifest is per route, so the per-locale split in `fonts-cyrillic.ts` /
 * `fonts-latin.ts` did what it looks like it does. Under Turbopack — the default
 * builder, and the one this app ships with — it is the project-wide UNION of
 * every declaration: measured on Next 16.2.12, `/`, `/en` and `_not-found` all
 * listed the same four files, so `/en` paid 53,488 B of top-priority Cyrillic
 * font bytes it can never draw a glyph from. Nothing arrangeable in the font
 * modules changes that; the union is by construction the RU set.
 *
 * So the automatic emission is turned off — every declaration passes
 * `preload: false` — and each layout emits its own links instead. That part is
 * exact: `/` gets four, `/en` gets two, and neither depends on a manifest.
 *
 * WHY THE URLS ARE GENERATED AND NOT TYPED. A preload has to name the very file
 * the `@font-face` rule names, and `next/font` writes content-hashed filenames
 * (`static/media/<hash>-s.<hash>.woff2`). A hardcoded one goes stale the day
 * Google reissues the font: the browser would then fetch a 404 at the highest
 * priority AND load the real file unpreloaded — worse than no preload at all.
 * This script therefore reads the URLs back out of the built CSS, which is the
 * same text the browser resolves `src:` from, so the two cannot disagree.
 *
 * WHY THE `.p.` MARKER MATTERS. `next/font` emits the same bytes under two
 * names: `<hash>-s.p.<hash>.woff2` when the declaration preloads that subset and
 * `<hash>-s.<hash>.woff2` when it does not. Turning preloading off therefore
 * changes the URL, and preloading the `.p.` name would fetch a second copy of a
 * file the page never uses. A `.p.` in the generated list is a hard error below.
 *
 * HOW IT CANNOT SILENTLY DESYNCHRONISE. Two layers, both under `--check`:
 *
 *   1. source — every `next/font/google` call really passes `preload: false`,
 *      every declared subset is one this script knows how to find, the two
 *      modules agree on the files they share, and no `.p.` name has crept in.
 *      Needs no build output, and runs first in `npm test`.
 *   2. build — the generated list is exactly the set of files the built CSS
 *      declares for those families and subsets. Runs whenever `.next` is there,
 *      and `npm run build` calls this script straight after `next build`, so a
 *      font that moved fails the build instead of shipping a dead preload.
 *
 * Run: node scripts/sync-font-preloads.mjs [--check]
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const DIST = join(ROOT, ".next");

/** The font modules, in the order their lists are reported. */
const MODULES = ["src/lib/fonts-cyrillic.ts", "src/lib/fonts-latin.ts"];

const OPEN = "// sync-font-preloads:begin ↓ generated by scripts/sync-font-preloads.mjs";
const CLOSE = "// sync-font-preloads:end ↑";

/**
 * One codepoint per Google Fonts subset that no other subset of the same family
 * covers — which is how a `@font-face` block is told apart without matching the
 * whole `unicode-range` string. `latin` is the only subset holding ASCII,
 * `cyrillic` the only one holding U+0410 (`cyrillic-ext` starts at U+0460),
 * `latin-ext` the only one holding U+0100, and so on. A subset that is declared
 * but missing here stops the script rather than guessing.
 */
const SUBSET_PROBE = {
  latin: 0x41,
  "latin-ext": 0x100,
  cyrillic: 0x410,
  "cyrillic-ext": 0x460,
  vietnamese: 0x1ea0,
};

const fail = (message) => {
  console.error(`✖ font preloads: ${message}`);
  process.exit(1);
};

/* ------------------------------------------------------------------ source */

/**
 * The `next/font/google` calls in one module: the CSS family name each loader
 * produces (`Golos_Text` → `Golos Text`) and the subsets it declares.
 */
function declarations(source, file) {
  const calls = [...source.matchAll(/\b([A-Z][A-Za-z0-9_]*)\(\{([\s\S]*?)\n\}\)/g)];
  if (calls.length === 0) fail(`${file}: no next/font/google declaration found`);

  return calls.map(([, loader, body]) => {
    if (!/\bpreload:\s*false\b/.test(body)) {
      fail(
        `${file}: ${loader}() does not pass \`preload: false\`.\n\n` +
          "  The links are emitted by hand here; leaving the automatic ones on\n" +
          "  would preload the `.p.` copies of the same files on every route.",
      );
    }
    const subsets = /\bsubsets:\s*\[([^\]]*)\]/.exec(body);
    if (!subsets) fail(`${file}: ${loader}() declares no \`subsets\``);
    const names = [...subsets[1].matchAll(/"([^"]+)"/g)].map(([, name]) => name);
    for (const name of names) {
      if (!(name in SUBSET_PROBE)) {
        fail(
          `${file}: ${loader}() declares the subset "${name}", which this script cannot locate.\n\n` +
            "  Add a codepoint only that subset covers to SUBSET_PROBE.",
        );
      }
    }
    return { loader, family: loader.replaceAll("_", " "), subsets: names };
  });
}

/* ------------------------------------------------------------------- build */

function cssFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return cssFiles(path);
    return name.endsWith(".css") ? [path] : [];
  });
}

/** `U+301,U+400-45F,U+??` → the intervals it stands for. */
function unicodeRange(text) {
  return text.split(",").map((token) => {
    const body = token.trim().replace(/^u\+/i, "");
    if (body.includes("-")) {
      const [from, to] = body.split("-");
      return [parseInt(from, 16), parseInt(to, 16)];
    }
    if (body.includes("?")) {
      return [parseInt(body.replaceAll("?", "0"), 16), parseInt(body.replaceAll("?", "F"), 16)];
    }
    const point = parseInt(body, 16);
    return [point, point];
  });
}

const covers = (ranges, point) => ranges.some(([from, to]) => point >= from && point <= to);

/** `../media/x.woff2` next to a chunk under `.next/` → the URL the browser asks for. */
function publicHref(cssFile, url) {
  const absolute = resolve(dirname(cssFile), url.replace(/^["']|["']$/g, ""));
  const inside = relative(DIST, absolute);
  if (inside.startsWith("..")) fail(`font file outside the build output: ${absolute}`);
  return `/_next/${inside.split(sep).join("/")}`;
}

/**
 * `family → subset → the files declared for it`. A set, not a single file:
 * a family shipped as static weights rather than one variable file declares a
 * separate woff2 per weight, and `next/font` preloads every one of them.
 */
function facesFromBuild() {
  const byFamily = new Map();
  for (const file of cssFiles(join(DIST, "static"))) {
    const css = readFileSync(file, "utf8");
    for (const [, block] of css.matchAll(/@font-face\s*\{([^}]*)\}/g)) {
      const family = /font-family:\s*([^;]+);/.exec(block);
      const src = /url\(([^)]+)\)/.exec(block);
      const range = /unicode-range:\s*([^;]+)[;}]?/.exec(block);
      if (!family || !src || !range) continue;

      const name = family[1].trim().replace(/^["']|["']$/g, "");
      const ranges = unicodeRange(range[1]);
      const bySubset = byFamily.get(name) ?? new Map();
      byFamily.set(name, bySubset);
      for (const [subset, probe] of Object.entries(SUBSET_PROBE)) {
        if (!covers(ranges, probe)) continue;
        const hrefs = bySubset.get(subset) ?? new Set();
        bySubset.set(subset, hrefs);
        hrefs.add(publicHref(file, src[1]));
      }
    }
  }
  return byFamily;
}

/* ------------------------------------------------------------------ region */

const escape = (text) => text.replaceAll(/[.*+?^${}()|[\]\\]/g, "\\$&");

function withRegion(source, file, hrefs) {
  const region = new RegExp(`^([ \\t]*)${escape(OPEN)}[\\s\\S]*?\\n[ \\t]*${escape(CLOSE)}`, "m");
  const found = region.exec(source);
  if (!found) fail(`${file}: no \`sync-font-preloads\` region`);
  const indent = found[1] ?? "";
  const body = hrefs.map((href) => `${indent}"${href}",`).join("\n");
  return source.replace(region, () => `${indent}${OPEN}\n${body}\n${indent}${CLOSE}`);
}

const listed = (source, file) => {
  const region = new RegExp(`${escape(OPEN)}([\\s\\S]*?)\\n[ \\t]*${escape(CLOSE)}`, "m");
  const found = region.exec(source);
  if (!found) fail(`${file}: no \`sync-font-preloads\` region`);
  return [...found[1].matchAll(/"([^"]+)"/g)].map(([, href]) => href);
};

/* -------------------------------------------------------------------- main */

const checking = process.argv.includes("--check");
const built = facesFromBuild();
const hasBuild = built.size > 0;

const modules = MODULES.map((file) => {
  const path = join(ROOT, file);
  const source = readFileSync(path, "utf8");
  return { file, path, source, fonts: declarations(source, file), hrefs: listed(source, file) };
});

// Layer 1 — the source, with no build output needed. The lists themselves are
// only judged when checking: writing replaces them wholesale.
if (checking) {
  for (const { file, hrefs } of modules) {
    if (hrefs.length === 0) {
      fail(`${file}: the preload list is empty — run \`node scripts/sync-font-preloads.mjs\``);
    }
    if (new Set(hrefs).size !== hrefs.length) fail(`${file}: the preload list repeats a file`);
    for (const href of hrefs) {
      if (/-s\.p\./.test(href)) {
        fail(
          `${file}: ${href} is a \`.p.\` name — the copy next/font emits for a subset it preloads itself.\n\n` +
            "  The page never loads that copy; preloading it downloads the font twice.",
        );
      }
      if (!href.startsWith("/_next/static/media/") || !href.endsWith(".woff2")) {
        fail(`${file}: ${href} is not a built woff2 file`);
      }
    }
  }

  const [cyrillic, latin] = modules;
  const missing = latin.hrefs.filter((href) => !cyrillic.hrefs.includes(href));
  if (missing.length > 0) {
    fail(
      `${latin.file} preloads a file ${cyrillic.file} does not: ${missing.join(", ")}.\n\n` +
        "  Both modules declare the same families and the same Latin subset, so the\n" +
        "  Latin files are the same bytes under the same name in both. A difference\n" +
        "  means one of the two lists was written against another build.",
    );
  }
}

if (!hasBuild) {
  if (!checking) fail("no build output — run `next build` first, the URLs are read back out of it");
  const links = modules.reduce((total, module) => total + module.hrefs.length, 0);
  console.log(
    `✔ font preloads: ${String(links)} links, source checks only` +
      " (no build output — `next build` first to check the URLs)",
  );
  process.exit(0);
}

// Layer 2 — the URLs, against the CSS the build actually wrote.
let stale = false;
for (const module of modules) {
  const wanted = [
    ...new Set(
      module.fonts.flatMap(({ family, subsets }) =>
        subsets.flatMap((subset) => {
          const hrefs = built.get(family)?.get(subset);
          if (!hrefs || hrefs.size === 0) {
            fail(`the build declares no "${subset}" face for ${family} — did the font move?`);
          }
          return [...hrefs];
        }),
      ),
    ),
  ].sort();

  const next = withRegion(module.source, module.file, wanted);
  if (next === module.source) continue;
  stale = true;
  if (!checking) writeFileSync(module.path, next);
}

if (!stale) {
  const summary = modules.map((m) => `${m.file}: ${String(m.hrefs.length)}`).join(", ");
  console.log(`✔ font preloads: ${summary} — every URL matches the built @font-face rules`);
  process.exit(0);
}
if (checking) {
  fail(
    "the generated lists no longer match the build's @font-face rules.\n\n" +
      "  Run `node scripts/sync-font-preloads.mjs` and commit the result.",
  );
}
console.log("✔ font preloads: rewritten from the built @font-face rules");
