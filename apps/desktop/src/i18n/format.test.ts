import { describe, expect, it } from "vitest";
import { format } from "./format";

describe("format", () => {
  it("подставляет параметры по имени", () => {
    expect(format("Предел — {limitMb} МБ", { limitMb: "32" })).toBe("Предел — 32 МБ");
  });

  it("подставляет один параметр в нескольких местах", () => {
    expect(format("{a} и ещё раз {a}", { a: "x" })).toBe("x и ещё раз x");
  });

  // Набор параметров зависит от ветки, которая породила ошибку: `details` есть у
  // отказа апстрима и нет у локального. Шаблон пишется под богатую ветку и
  // обязан выродиться в чистую фразу, а не показать `{details}`.
  it("дырку без значения вырезает вместе с хвостовой пунктуацией", () => {
    expect(format("Проверьте интернет или VPN. {details}")).toBe("Проверьте интернет или VPN.");
    expect(format("Попробуйте позже: {details}")).toBe("Попробуйте позже");
    expect(format("{details}")).toBe("");
  });

  it("схлопывает двойные пробелы, оставшиеся от вырезанной дырки", () => {
    expect(format("до {gone} после")).toBe("до после");
  });

  it("шаблон без дырок отдаётся как есть", () => {
    expect(format("Остановлено.")).toBe("Остановлено.");
  });
});
